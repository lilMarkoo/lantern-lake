SPACE = 3
UNKNOWN = (0, ['###', '#.#', '#.#', '#.#', '#.#', '#.#', '###'])


def _mask(ch, bold=False):
    top, rows = GLYPHS.get(ch, UNKNOWN)
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    if bold:
        # thicken strokes to the right, but never close a one-pixel gap (keeps m, w and B readable)
        thick = []
        for r in rows:
            out = list(r + '.')
            for x, c in enumerate(r):
                right = r[x + 1] if x + 1 < w else '.'
                right2 = r[x + 2] if x + 2 < w else '.'
                if c == '#' and right == '.' and right2 == '.':
                    out[x + 1] = '#'
            thick.append(''.join(out))
        rows = thick
        w += 1
    m = pygame.Surface((w, ROWS), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == '#':
                m.set_at((x, top + y), (255, 255, 255, 255))
    return m


_MASKS = {}


def mask(ch, bold=False):
    m = _MASKS.get((ch, bold))
    if m is None:
        m = _MASKS[(ch, bold)] = _mask(ch, bold)
    return m


class PixelFont:
    """Looks enough like pygame.font.Font for this game: size(), render(), get_height(), get_linesize()."""

    def __init__(self, px=2, bold=False, spacing=1):
        self.px = px
        self.bold = bold
        self.spacing = spacing

    def _advance(self, ch):
        if ch == ' ':
            return SPACE + self.spacing
        return mask(ch, self.bold).get_width() + self.spacing

    def grid_width(self, text):
        if not text:
            return 0
        cache = self.__dict__.setdefault('_widths', {})    # the HUD measures the same few strings every frame
        w = cache.get(text)
        if w is None:
            if len(cache) > 4000:
                cache.clear()
            w = cache[text] = sum(self._advance(c) for c in text) - self.spacing
        return w

    def size(self, text):
        return (max(1, self.grid_width(text)) * self.px, LINE * self.px)

    def get_height(self):
        return LINE * self.px

    def get_linesize(self):
        return LINE * self.px

    def render(self, text, antialias=False, color=(0, 0, 0), background=None):
        gw = max(1, self.grid_width(text))
        small = pygame.Surface((gw, LINE), pygame.SRCALPHA)
        x = 0
        for ch in text:
            if ch != ' ':
                small.blit(mask(ch, self.bold), (x, 0))
            x += self._advance(ch)
        tint = pygame.Surface(small.get_size(), pygame.SRCALPHA)
        tint.fill((*color[:3], 255))
        small.blit(tint, (0, 0), special_flags=pygame.BLEND_RGBA_MULT)
        out = pygame.transform.scale(small, (gw * self.px, LINE * self.px))
        if background is not None:
            bg = pygame.Surface(out.get_size())
            bg.fill(background)
            bg.blit(out, (0, 0))
            return bg
        return out
